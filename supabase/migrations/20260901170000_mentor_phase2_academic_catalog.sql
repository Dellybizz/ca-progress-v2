-- Existing syllabus_versions.supersedes_version_id is preserved and exposed in both directions.
create view public.academic_syllabus_lineage
with (security_invoker = true)
as
select
  predecessor.id as predecessor_version_id,
  successor.id as successor_version_id,
  predecessor.subject_id,
  predecessor.version_key as predecessor_version_key,
  successor.version_key as successor_version_key,
  successor.effective_from
from public.syllabus_versions successor
join public.syllabus_versions predecessor on predecessor.id = successor.supersedes_version_id;

-- Item lineage is deliberately not inferred from title similarity. When a future syllabus
-- splits/merges/replaces a concept, the explicit academic_catalog_lineage table records it.

create or replace function public.academic_catalog_resolve_legacy(
  p_entity_type text,
  p_entity_id text,
  p_syllabus_version_id text default null
)
returns text
language sql
stable
set search_path = public, pg_temp
as $$
  select case
    when count(distinct vi.canonical_id) = 1 then min(vi.canonical_id)
    else null
  end
  from public.academic_catalog_version_items vi
  where vi.source_entity_type = p_entity_type
    and vi.source_entity_id = p_entity_id
    and (p_syllabus_version_id is null or vi.syllabus_version_id = p_syllabus_version_id);
$$;

create or replace function public.academic_catalog_is_applicable(
  p_canonical_id text,
  p_attempt_key text
)
returns boolean
language sql
stable
set search_path = public, pg_temp
as $$
  select exists (
    select 1
    from public.academic_catalog_version_items vi
    join public.attempt_syllabus_map asm
      on asm.syllabus_version_id = vi.syllabus_version_id
    where vi.canonical_id = p_canonical_id
      and asm.attempt_key = p_attempt_key
  );
$$;

create or replace function public.academic_catalog_resolve_alias(
  p_alias text,
  p_attempt_key text default null,
  p_subject_id text default null,
  p_node_type text default null
)
returns table (
  canonical_id text,
  node_type text,
  title text,
  official_code text,
  syllabus_version_id text
)
language sql
stable
set search_path = public, pg_temp
as $$
  select distinct
    n.canonical_id,
    n.node_type,
    n.title,
    n.official_code,
    vi.syllabus_version_id
  from public.academic_catalog_aliases a
  join public.academic_catalog_nodes n on n.canonical_id = a.canonical_id
  left join public.academic_catalog_version_items vi on vi.canonical_id = n.canonical_id
  where a.is_active
    and a.normalized_alias = trim(regexp_replace(lower(p_alias), '[^a-z0-9]+', ' ', 'g'))
    and (p_subject_id is null or n.subject_id = p_subject_id)
    and (p_node_type is null or n.node_type = p_node_type)
    and (
      p_attempt_key is null
      or public.academic_catalog_is_applicable(n.canonical_id, p_attempt_key)
    )
  order by n.node_type, n.title, vi.syllabus_version_id nulls last;
$$;

create or replace function public.academic_catalog_resolve_alias_one(
  p_alias text,
  p_attempt_key text default null,
  p_subject_id text default null,
  p_node_type text default null
)
returns text
language sql
stable
set search_path = public, pg_temp
as $$
  select case
    when count(distinct candidate.canonical_id) = 1 then min(candidate.canonical_id)
    else null
  end
  from public.academic_catalog_resolve_alias(p_alias, p_attempt_key, p_subject_id, p_node_type) candidate;
$$;

-- Canonical progress views map old/current chapter IDs without rewriting a single progress row.
create view public.chapter_progress_canonical
with (security_invoker = true)
as
select
  cp.user_id,
  cp.chapter_id,
  vi.canonical_id,
  vi.syllabus_version_id,
  vi.official_code as chapter_number,
  cp.completed_at,
  cp.revision_1_at,
  cp.revision_2_at,
  cp.test_1_at,
  cp.test_2_at,
  cp.created_at,
  cp.updated_at
from public.chapter_progress cp
join public.chapters c on c.id = cp.chapter_id
join public.academic_catalog_version_items vi
  on vi.source_entity_type = 'chapter'
 and vi.source_entity_id = cp.chapter_id
 and vi.syllabus_version_id = c.syllabus_version_id;

create view public.progress_events_canonical
with (security_invoker = true)
as
select
  pe.id,
  pe.user_id,
  pe.chapter_id,
  vi.canonical_id,
  vi.syllabus_version_id,
  vi.official_code as chapter_number,
  pe.stage,
  pe.action,
  pe.previous_state,
  pe.new_state,
  pe.reverts_event_id,
  pe.undone_at,
  pe.created_at
from public.progress_events pe
join public.chapters c on c.id = pe.chapter_id
join public.academic_catalog_version_items vi
  on vi.source_entity_type = 'chapter'
 and vi.source_entity_id = pe.chapter_id
 and vi.syllabus_version_id = c.syllabus_version_id;

