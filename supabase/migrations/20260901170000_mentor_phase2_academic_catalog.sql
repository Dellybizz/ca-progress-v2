with chapter_candidates as (
  select
    'chapter:' || s.id || ':' || c.stable_key as canonical_id,
    'subject:' || s.id as parent_canonical_id,
    s.level_id,
    s.group_id,
    s.id as subject_id,
    c.chapter_number as official_code,
    c.title,
    (sv.status = 'published') as is_active,
    sv.effective_from,
    sv.status
  from public.chapters c
  join public.syllabus_versions sv on sv.id = c.syllabus_version_id
  join public.subjects s on s.id = sv.subject_id
),
chapter_current as (
  select distinct on (canonical_id)
    canonical_id, parent_canonical_id, level_id, group_id, subject_id, official_code, title, is_active
  from chapter_candidates
  order by canonical_id, (status = 'published') desc, effective_from desc
)
insert into public.academic_catalog_nodes (
  canonical_id, node_type, parent_canonical_id, level_id, group_id, subject_id, official_code, title, is_active
)
select
  canonical_id, 'chapter', parent_canonical_id, level_id, group_id, subject_id, official_code, title, is_active
from chapter_current
on conflict (canonical_id) do nothing;

with topic_candidates as (
  select
    'topic:' || s.id || ':' || c.stable_key || ':' || t.stable_key as canonical_id,
    case
      when t.topic_kind = 'accounting_standard' then 'accounting_standard'
      when t.topic_kind = 'unit' then 'unit'
      else 'subtopic'
    end as node_type,
    'chapter:' || s.id || ':' || c.stable_key as parent_canonical_id,
    s.level_id,
    s.group_id,
    s.id as subject_id,
    t.unit_number as official_code,
    t.title,
    (sv.status = 'published') as is_active,
    sv.effective_from,
    sv.status
  from public.topics t
  join public.chapters c on c.id = t.chapter_id
  join public.syllabus_versions sv on sv.id = c.syllabus_version_id
  join public.subjects s on s.id = sv.subject_id
),
topic_current as (
  select distinct on (canonical_id)
    canonical_id, node_type, parent_canonical_id, level_id, group_id, subject_id, official_code, title, is_active
  from topic_candidates
  order by canonical_id, (status = 'published') desc, effective_from desc
)
insert into public.academic_catalog_nodes (
  canonical_id, node_type, parent_canonical_id, level_id, group_id, subject_id, official_code, title, is_active
)
select
  canonical_id, node_type, parent_canonical_id, level_id, group_id, subject_id, official_code, title, is_active
from topic_current
on conflict (canonical_id) do nothing;

