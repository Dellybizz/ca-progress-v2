-- CA Progress V2 — CA Mentor / Think Engine Phase 2: Academic Catalog Normalisation
-- Reuses the existing verified academic engine. No source ingestion is added here.
-- Existing chapter_progress/progress_events rows remain untouched; canonical mappings are additive.

create table public.academic_catalog_nodes (
  canonical_id text primary key,
  node_type text not null check (node_type in ('course', 'group', 'subject', 'chapter', 'unit', 'accounting_standard', 'subtopic')),
  parent_canonical_id text references public.academic_catalog_nodes(canonical_id) on delete restrict,
  level_id text not null references public.course_levels(id) on delete restrict,
  group_id text references public.course_groups(id) on delete restrict,
  subject_id text references public.subjects(id) on delete restrict,
  official_code text,
  title text not null,
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.academic_catalog_version_items (
  id bigint generated by default as identity primary key,
  canonical_id text not null references public.academic_catalog_nodes(canonical_id) on delete restrict,
  syllabus_version_id text not null references public.syllabus_versions(id) on delete restrict,
  source_entity_type text not null check (source_entity_type in ('subject', 'chapter', 'topic')),
  source_entity_id text not null,
  source_stable_key text,
  source_topic_kind text,
  official_code text,
  display_title text not null,
  applicable_from date not null,
  applicable_to date,
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  check (applicable_to is null or applicable_to >= applicable_from),
  unique (syllabus_version_id, source_entity_type, source_entity_id)
);

create table public.academic_catalog_aliases (
  id bigint generated by default as identity primary key,
  canonical_id text not null references public.academic_catalog_nodes(canonical_id) on delete cascade,
  alias_text text not null check (length(trim(alias_text)) > 0),
  normalized_alias text generated always as (
    trim(regexp_replace(lower(alias_text), '[^a-z0-9]+', ' ', 'g'))
  ) stored,
  alias_kind text not null check (alias_kind in ('official_title', 'official_code', 'legacy_title', 'slug', 'stable_key', 'manual')),
  subject_id text references public.subjects(id) on delete restrict,
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  unique (canonical_id, normalized_alias)
);

create table public.academic_catalog_lineage (
  predecessor_canonical_id text not null references public.academic_catalog_nodes(canonical_id) on delete restrict,
  successor_canonical_id text not null references public.academic_catalog_nodes(canonical_id) on delete restrict,
  relationship text not null check (relationship in ('renamed_to', 'superseded_by', 'split_into', 'merged_into', 'equivalent_to')),
  effective_from date,
  notes text,
  created_at timestamptz not null default now(),
  primary key (predecessor_canonical_id, successor_canonical_id, relationship),
  check (predecessor_canonical_id <> successor_canonical_id)
);

create index academic_catalog_nodes_parent_idx on public.academic_catalog_nodes (parent_canonical_id, node_type);
create index academic_catalog_nodes_scope_idx on public.academic_catalog_nodes (level_id, group_id, subject_id, node_type);
create index academic_catalog_version_items_canonical_idx on public.academic_catalog_version_items (canonical_id, syllabus_version_id);
create index academic_catalog_version_items_source_idx on public.academic_catalog_version_items (source_entity_type, source_entity_id);
create index academic_catalog_aliases_lookup_idx on public.academic_catalog_aliases (normalized_alias, subject_id);
create index academic_catalog_lineage_successor_idx on public.academic_catalog_lineage (successor_canonical_id);

create trigger academic_catalog_nodes_set_updated_at
before update on public.academic_catalog_nodes
for each row execute function public.set_updated_at();

