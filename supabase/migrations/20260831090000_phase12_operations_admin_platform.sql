create or replace function public.phase12_upsert_notification_template(p_actor uuid,p_id uuid,p_template_key text,p_name text,p_title text,p_body text,p_active boolean,p_request_id uuid)
returns jsonb language plpgsql security definer set search_path=public,auth,pg_temp as $$
declare v_role text; v_id uuid; v_before jsonb:='{}'::jsonb;
begin
 v_role:=public.phase12_assert_role(p_actor,20);
 if p_id is not null then select to_jsonb(t) into v_before from public.notification_templates t where id=p_id; end if;
 if p_template_key !~ '^[a-z0-9._-]{3,100}$' or char_length(trim(p_name))<1 or char_length(trim(p_title))<1 or char_length(p_body)<1 then raise exception 'Template fields are invalid.'; end if;
 if p_id is null then
   insert into public.notification_templates(template_key,name,title,body,is_active,updated_by) values(p_template_key,trim(p_name),trim(p_title),p_body,p_active,p_actor) returning id into v_id;
 else
   update public.notification_templates set template_key=p_template_key,name=trim(p_name),title=trim(p_title),body=p_body,is_active=p_active,updated_by=p_actor,updated_at=now() where id=p_id returning id into v_id;
   if v_id is null then raise exception 'Notification template not found.'; end if;
 end if;
 insert into public.admin_audit_logs(actor_user_id,actor_role,action_key,entity_type,entity_id,request_id,before_state,after_state)
 select p_actor,v_role,'notifications.template_saved','notification_template',v_id::text,p_request_id,v_before,to_jsonb(t) from public.notification_templates t where id=v_id;
 return jsonb_build_object('ok',true,'id',v_id);
end; $$;

