-- CA Progress V2 — Phase 12 Operations Admin Platform
-- V2 only. Existing privileged JWT roles are bootstrapped; this migration never invents an operator.

create table public.admin_users (
  user_id uuid primary key references auth.users(id) on delete cascade,
  role text not null check (role in ('moderator','admin','owner','parent_owner')),
  is_active boolean not null default true,
  granted_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.admin_audit_logs (
  id bigint generated by default as identity primary key,
  actor_user_id uuid references auth.users(id) on delete set null,
  actor_role text not null check (actor_role in ('system','moderator','admin','owner','parent_owner')),
  action_key text not null check (char_length(action_key) between 3 and 120),
  entity_type text not null check (char_length(entity_type) between 2 and 80),
  entity_id text,
  request_id uuid not null unique,
  before_state jsonb not null default '{}'::jsonb check (jsonb_typeof(before_state)='object'),
  after_state jsonb not null default '{}'::jsonb check (jsonb_typeof(after_state)='object'),
  metadata jsonb not null default '{}'::jsonb check (jsonb_typeof(metadata)='object'),
  created_at timestamptz not null default now()
);

create table public.feature_flags (
  flag_key text primary key check (flag_key ~ '^[a-z0-9._-]{3,100}$'),
  label text not null,
  description text not null default '',
  enabled boolean not null default true,
  updated_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.maintenance_settings (
  id boolean primary key default true check (id),
  enabled boolean not null default false,
  message text not null default 'CA Progress is temporarily in maintenance mode.',
  starts_at timestamptz,
  ends_at timestamptz,
  updated_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  check (ends_at is null or starts_at is null or ends_at > starts_at)
);

create table public.notification_templates (
  id uuid primary key default gen_random_uuid(),
  template_key text not null unique check (template_key ~ '^[a-z0-9._-]{3,100}$'),
  name text not null check (char_length(name) between 1 and 120),
  title text not null check (char_length(title) between 1 and 180),
  body text not null check (char_length(body) between 1 and 4000),
  is_active boolean not null default true,
  updated_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index admin_users_role_active_idx on public.admin_users(role,is_active,user_id);
create index admin_audit_logs_created_idx on public.admin_audit_logs(created_at desc,id desc);
create index admin_audit_logs_actor_idx on public.admin_audit_logs(actor_user_id,created_at desc);
create index admin_audit_logs_entity_idx on public.admin_audit_logs(entity_type,entity_id,created_at desc);
create index notification_templates_active_idx on public.notification_templates(is_active,updated_at desc);

create trigger admin_users_set_updated_at before update on public.admin_users for each row execute function public.set_updated_at();
create trigger feature_flags_set_updated_at before update on public.feature_flags for each row execute function public.set_updated_at();
create trigger maintenance_settings_set_updated_at before update on public.maintenance_settings for each row execute function public.set_updated_at();
create trigger notification_templates_set_updated_at before update on public.notification_templates for each row execute function public.set_updated_at();

