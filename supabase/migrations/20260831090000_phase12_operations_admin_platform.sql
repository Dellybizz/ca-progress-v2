 if p_ends_at is not null and p_starts_at is not null and p_ends_at<=p_starts_at then raise exception 'Maintenance window is invalid.'; end if;
 update public.maintenance_settings set enabled=p_enabled,message=trim(p_message),starts_at=p_starts_at,ends_at=p_ends_at,updated_by=p_actor,updated_at=now() where id=true;
