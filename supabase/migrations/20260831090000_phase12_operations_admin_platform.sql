create or replace function public.phase12_role_rank(p_role text)
returns integer language sql immutable set search_path=public as $$
 select case p_role when 'moderator' then 10 when 'admin' then 20 when 'owner' then 30 when 'parent_owner' then 40 else 0 end;
$$;

create or replace function public.phase12_admin_role(p_user_id uuid)
returns text language sql stable security definer set search_path=public,auth,pg_temp as $$
 select role from public.admin_users where user_id=p_user_id and is_active limit 1;
$$;

create or replace function public.phase12_get_my_admin_role()
returns text language sql stable security definer set search_path=public,auth,pg_temp as $$
 select public.phase12_admin_role(auth.uid());
$$;

create or replace function public.phase12_assert_role(p_actor uuid,p_min_rank integer)
returns text language plpgsql stable security definer set search_path=public,auth,pg_temp as $$
declare v_role text;
begin
 select role into v_role from public.admin_users where user_id=p_actor and is_active;
 if v_role is null or public.phase12_role_rank(v_role)<p_min_rank then raise exception 'Admin authorization required.' using errcode='42501'; end if;
 return v_role;
end; $$;

create or replace function public.phase12_bootstrap_parent_owner(p_user_id uuid,p_request_id uuid)
returns jsonb language plpgsql security definer set search_path=public,auth,pg_temp as $$
declare v_email text;
begin
 if exists(select 1 from public.admin_users where role='parent_owner' and is_active) then raise exception 'An active parent owner already exists.' using errcode='42501'; end if;
 select email into v_email from auth.users where id=p_user_id;
 if v_email is null then raise exception 'Target auth user not found.'; end if;
 insert into public.admin_users(user_id,role,is_active) values(p_user_id,'parent_owner',true)
 on conflict(user_id) do update set role='parent_owner',is_active=true,updated_at=now();
 insert into public.admin_audit_logs(actor_user_id,actor_role,action_key,entity_type,entity_id,request_id,after_state,metadata)
 values(null,'system','admin.bootstrap_parent_owner','admin_user',p_user_id::text,p_request_id,jsonb_build_object('role','parent_owner','active',true),jsonb_build_object('email',v_email));
 return jsonb_build_object('ok',true,'userId',p_user_id);
end; $$;

create or replace function public.phase12_set_admin_role(p_actor uuid,p_target uuid,p_new_role text,p_request_id uuid)
returns jsonb language plpgsql security definer set search_path=public,auth,pg_temp as $$
declare v_actor_role text; v_target public.admin_users%rowtype; v_before jsonb; v_after jsonb;
begin
 v_actor_role:=public.phase12_assert_role(p_actor,30);
 if p_actor=p_target then raise exception 'Self-demotion or self-role changes are not allowed.' using errcode='42501'; end if;
 if p_new_role not in ('moderator','admin','owner') then raise exception 'parent_owner cannot be assigned through the application.' using errcode='42501'; end if;
 select * into v_target from public.admin_users where user_id=p_target;
 if found and v_target.role='parent_owner' then raise exception 'The parent owner role is protected.' using errcode='42501'; end if;
 if found and public.phase12_role_rank(v_actor_role)<=public.phase12_role_rank(v_target.role) then raise exception 'Operators cannot modify an equal or higher role.' using errcode='42501'; end if;
 if public.phase12_role_rank(v_actor_role)<=public.phase12_role_rank(p_new_role) then raise exception 'Operators cannot grant an equal or higher role.' using errcode='42501'; end if;
 if not exists(select 1 from auth.users where id=p_target) then raise exception 'Target auth user not found.'; end if;
 v_before:=case when found then jsonb_build_object('role',v_target.role,'active',v_target.is_active) else '{}'::jsonb end;
 insert into public.admin_users(user_id,role,is_active,granted_by) values(p_target,p_new_role,true,p_actor)
 on conflict(user_id) do update set role=excluded.role,is_active=true,granted_by=p_actor,updated_at=now();
 v_after:=jsonb_build_object('role',p_new_role,'active',true);
 insert into public.admin_audit_logs(actor_user_id,actor_role,action_key,entity_type,entity_id,request_id,before_state,after_state)
 values(p_actor,v_actor_role,'admin.role_changed','admin_user',p_target::text,p_request_id,v_before,v_after);
 return jsonb_build_object('ok',true,'userId',p_target,'role',p_new_role);
end; $$;

create or replace function public.phase12_set_admin_active(p_actor uuid,p_target uuid,p_active boolean,p_request_id uuid)
returns jsonb language plpgsql security definer set search_path=public,auth,pg_temp as $$
declare v_actor_role text; v_target public.admin_users%rowtype;
begin
 v_actor_role:=public.phase12_assert_role(p_actor,30);
 if p_actor=p_target then raise exception 'Operators cannot deactivate themselves.' using errcode='42501'; end if;
 select * into v_target from public.admin_users where user_id=p_target;
 if not found then raise exception 'Admin user not found.'; end if;
 if v_target.role='parent_owner' then raise exception 'The parent owner cannot be deactivated.' using errcode='42501'; end if;
 if public.phase12_role_rank(v_actor_role)<=public.phase12_role_rank(v_target.role) then raise exception 'Operators cannot modify an equal or higher role.' using errcode='42501'; end if;
 update public.admin_users set is_active=p_active,updated_at=now() where user_id=p_target;
 insert into public.admin_audit_logs(actor_user_id,actor_role,action_key,entity_type,entity_id,request_id,before_state,after_state)
 values(p_actor,v_actor_role,'admin.access_toggled','admin_user',p_target::text,p_request_id,jsonb_build_object('active',v_target.is_active,'role',v_target.role),jsonb_build_object('active',p_active,'role',v_target.role));
 return jsonb_build_object('ok',true,'active',p_active);
end; $$;

create or replace function public.phase12_list_members(p_actor uuid,p_page integer default 1,p_limit integer default 25,p_search text default null,p_role text default null)
returns table(user_id uuid,email text,display_name text,role text,admin_active boolean,plan_tier text,plan_name text,subscription_ends_at timestamptz,user_created_at timestamptz,total_count bigint)
language plpgsql stable security definer set search_path=public,auth,pg_temp as $$
begin
 perform public.phase12_assert_role(p_actor,20);
 if p_page<1 or p_limit<1 or p_limit>100 then raise exception 'Invalid pagination.'; end if;
 return query
 with members as (
   select u.id,u.email,coalesce(nullif(u.raw_user_meta_data->>'full_name',''),nullif(u.raw_user_meta_data->>'name',''),split_part(coalesce(u.email,''),'@',1)) as display_name,
          au.role,coalesce(au.is_active,false) admin_active,p.tier_key,p.name,
          (select us.ends_at from public.user_subscriptions us where us.user_id=u.id and us.plan_id=p.id and us.status='active' and us.starts_at<=now() and (us.ends_at is null or us.ends_at>now()) order by us.created_at desc limit 1) as subscription_ends_at,
          u.created_at
   from auth.users u
   left join public.admin_users au on au.user_id=u.id
   left join public.subscription_plans p on p.id=public.phase11_current_plan_id(u.id)
   where (p_search is null or p_search='' or lower(coalesce(u.email,'')) like '%'||lower(p_search)||'%' or lower(coalesce(u.raw_user_meta_data->>'full_name',u.raw_user_meta_data->>'name','')) like '%'||lower(p_search)||'%')
     and (p_role is null or p_role='' or coalesce(au.role,'student')=p_role)
 )
 select m.id,m.email,m.display_name,coalesce(m.role,'student'),m.admin_active,coalesce(m.tier_key,'free'),coalesce(m.name,'Free'),m.subscription_ends_at,m.created_at,count(*) over()
 from members m order by m.created_at desc,m.id desc limit p_limit offset ((p_page-1)*p_limit);
end; $$;

