create or replace function public.phase12_update_content_state(p_actor uuid,p_entity_type text,p_entity_id text,p_status text,p_verification_status text,p_request_id uuid)
returns jsonb language plpgsql security definer set search_path=public,auth,pg_temp as $$
declare v_role text; v_before jsonb; v_after jsonb;
begin
 v_role:=public.phase12_assert_role(p_actor,20);
 if p_entity_type='syllabus_version' then
   select to_jsonb(s) into v_before from public.syllabus_versions s where id=p_entity_id; if v_before is null then raise exception 'Syllabus version not found.'; end if;
   if p_status not in ('published','superseded','upcoming') then raise exception 'Invalid syllabus status.'; end if;
   update public.syllabus_versions set status=p_status,updated_at=now() where id=p_entity_id; select to_jsonb(s) into v_after from public.syllabus_versions s where id=p_entity_id;
 elsif p_entity_type='exam_attempt' then
   select to_jsonb(a) into v_before from public.exam_attempts a where id=p_entity_id; if v_before is null then raise exception 'Exam attempt not found.'; end if;
   if p_status not in ('scheduled','open','completed','cancelled') or p_verification_status not in ('verified','pending_review','rejected') then raise exception 'Invalid attempt state.'; end if;
   update public.exam_attempts set status=p_status,verification_status=p_verification_status,verification_method='admin_review',updated_at=now() where id=p_entity_id; select to_jsonb(a) into v_after from public.exam_attempts a where id=p_entity_id;
 elsif p_entity_type='icai_resource' then
   select to_jsonb(r) into v_before from public.icai_resources r where id=p_entity_id; if v_before is null then raise exception 'ICAI resource not found.'; end if;
   if p_status not in ('active','removed','replaced') or p_verification_status not in ('verified','pending_review','rejected') then raise exception 'Invalid resource state.'; end if;
   update public.icai_resources set status=p_status,verification_status=p_verification_status,updated_at=now() where id=p_entity_id; select to_jsonb(r) into v_after from public.icai_resources r where id=p_entity_id;
 else raise exception 'Unsupported content entity.';
 end if;
 insert into public.admin_audit_logs(actor_user_id,actor_role,action_key,entity_type,entity_id,request_id,before_state,after_state)
 values(p_actor,v_role,'content.state_changed',p_entity_type,p_entity_id,p_request_id,v_before,v_after);
 return jsonb_build_object('ok',true);
end; $$;

