create or replace function public.phase12_set_maintenance(p_actor uuid,p_enabled boolean,p_message text,p_starts_at timestamptz,p_ends_at timestamptz,p_request_id uuid)
returns jsonb language plpgsql security definer set search_path=public,auth,pg_temp as $$
declare v_role text; v_before public.maintenance_settings%rowtype;
begin
 v_role:=public.phase12_assert_role(p_actor,30); select * into v_before from public.maintenance_settings where id=true;
