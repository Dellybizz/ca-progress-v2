 values(p_actor,v_role,'platform.maintenance_changed','maintenance','global',p_request_id,to_jsonb(v_before)-'id'-'created_at'-'updated_at',jsonb_build_object('enabled',p_enabled,'message',trim(p_message),'starts_at',p_starts_at,'ends_at',p_ends_at));
 return jsonb_build_object('ok',true,'enabled',p_enabled);
