create or replace function public.phase10_list_channels()
returns table (
  id uuid,
  channel_key text,
  slug text,
  scope_type text,
  channel_kind text,
  title text,
  description text,
  level_id text,
  subject_id text,
  write_policy text,
  sort_order integer,
  can_write boolean,
  unread_count bigint,
  latest_sequence bigint,
  latest_body text,
  latest_author text,
  latest_at timestamptz
)
language sql
stable
security definer
set search_path = public, auth, pg_temp
as $$
  select c.id,c.channel_key,c.slug,c.scope_type,c.channel_kind,c.title,c.description,c.level_id,c.subject_id,c.write_policy,c.sort_order,
         public.phase10_can_write_channel(c.id),
         (select count(*) from public.community_messages m
          where m.channel_id=c.id and m.moderation_status='active' and m.user_id<>auth.uid()
            and m.sequence_id>coalesce((select r.last_read_sequence from public.channel_read_state r where r.channel_id=c.id and r.user_id=auth.uid()),0))::bigint,
         latest.sequence_id,latest.body,latest.author_label,latest.created_at
  from public.community_channels c
  left join lateral (
    select m.sequence_id,m.body,m.author_label,m.created_at
    from public.community_messages m
    where m.channel_id=c.id and m.moderation_status='active'
    order by m.sequence_id desc limit 1
  ) latest on true
  where c.is_active=true and public.phase10_can_view_channel(c.id)
  order by c.sort_order,c.title;
$$;

create or replace function public.phase10_list_channel_members(p_channel_key text, p_limit integer default 100)
returns table (user_id uuid, label text)
language plpgsql
stable
security definer
set search_path = public, auth, pg_temp
as $$
declare v_channel_id uuid;
begin
  select c.id into v_channel_id from public.community_channels c where c.channel_key=p_channel_key and c.is_active=true;
  if v_channel_id is null or not public.phase10_can_view_channel(v_channel_id) then raise exception 'Channel access denied.' using errcode='42501'; end if;
  return query
    select p.user_id,coalesce(nullif(btrim(p.display_name),''),'Student')
    from public.profiles p
    where p.onboarding_completed_at is not null and public.phase10_channel_visible_to_user(v_channel_id,p.user_id)
    order by coalesce(nullif(btrim(p.display_name),''),'Student')
    limit greatest(1,least(coalesce(p_limit,100),200));
end;
$$;

create or replace function public.phase10_create_message(
  p_channel_key text,
  p_body text,
  p_reply_to_message_id uuid default null,
  p_attached_resource_id uuid default null,
  p_mention_user_ids uuid[] default '{}'::uuid[]
)
returns uuid
language plpgsql
security definer
set search_path = public, auth, pg_temp
as $$
declare
  v_user_id uuid := auth.uid();
  v_channel public.community_channels;
  v_message_id uuid;
  v_author_label text;
  v_reply_user uuid;
  v_mentions uuid[] := coalesce(p_mention_user_ids,'{}'::uuid[]);
begin
  if v_user_id is null then raise exception 'Authentication required.' using errcode='42501'; end if;
  select * into v_channel from public.community_channels where channel_key=p_channel_key and is_active=true;
  if not found or not public.phase10_can_write_channel(v_channel.id) then raise exception 'You cannot write to this channel.' using errcode='42501'; end if;
  p_body := regexp_replace(coalesce(p_body,''),'[[:space:]]+',' ','g');
  p_body := btrim(p_body);
  if char_length(p_body) < 1 or char_length(p_body) > 2000 then raise exception 'Messages must be between 1 and 2000 characters.' using errcode='22023'; end if;
  if coalesce(array_length(v_mentions,1),0) > 10 then raise exception 'A message can mention at most 10 people.' using errcode='22023'; end if;

  if (select count(*) from public.community_messages m where m.user_id=v_user_id and m.created_at>now()-interval '60 seconds') >= 12 then
    raise exception 'Message rate limit reached. Try again in a moment.' using errcode='P0001';
  end if;
  if exists (select 1 from public.community_messages m where m.user_id=v_user_id and m.channel_id=v_channel.id and lower(btrim(m.body))=lower(p_body) and m.created_at>now()-interval '90 seconds' and m.moderation_status='active') then
    raise exception 'Duplicate message blocked.' using errcode='P0001';
  end if;

  if p_reply_to_message_id is not null then
    select user_id into v_reply_user from public.community_messages where id=p_reply_to_message_id and channel_id=v_channel.id and moderation_status='active';
    if v_reply_user is null then raise exception 'Reply target is unavailable.' using errcode='22023'; end if;
  end if;

  if p_attached_resource_id is not null and not exists (
    select 1 from public.uploaded_resources u where u.id=p_attached_resource_id and u.visibility='shared' and u.moderation_status='approved'
  ) then raise exception 'Only approved shared resources can be attached.' using errcode='42501'; end if;

  select coalesce(nullif(btrim(display_name),''),'Student') into v_author_label from public.profiles where user_id=v_user_id;
  v_author_label := coalesce(v_author_label,'Student');

  insert into public.community_messages (channel_id,user_id,author_label,body,reply_to_message_id,attached_resource_id)
  values (v_channel.id,v_user_id,v_author_label,p_body,p_reply_to_message_id,p_attached_resource_id)
  returning id into v_message_id;

  insert into public.community_message_mentions (message_id,user_id)
  select v_message_id,x.user_id
  from (select distinct unnest(v_mentions) as user_id) x
  where x.user_id<>v_user_id and public.phase10_channel_visible_to_user(v_channel.id,x.user_id)
  on conflict do nothing;

  insert into public.community_notifications (user_id,notification_type,channel_id,message_id)
  select mm.user_id,'mention',v_channel.id,v_message_id
  from public.community_message_mentions mm where mm.message_id=v_message_id
  on conflict do nothing;

  if v_reply_user is not null and v_reply_user<>v_user_id then
    insert into public.community_notifications (user_id,notification_type,channel_id,message_id)
    values (v_reply_user,'reply',v_channel.id,v_message_id)
    on conflict do nothing;
  end if;

  if v_channel.channel_kind='announcements' and public.phase10_is_moderator() then
    insert into public.community_notifications (user_id,notification_type,channel_id,message_id)
    select p.user_id,'announcement',v_channel.id,v_message_id
    from public.profiles p
    where p.user_id<>v_user_id and p.onboarding_completed_at is not null and public.phase10_channel_visible_to_user(v_channel.id,p.user_id)
    on conflict do nothing;
  end if;

  return v_message_id;
end;
$$;

create or replace function public.phase10_mark_read(p_channel_key text, p_sequence_id bigint default null)
returns bigint
language plpgsql
security definer
set search_path = public, auth, pg_temp
as $$
declare v_user_id uuid:=auth.uid(); v_channel_id uuid; v_sequence bigint;
begin
  if v_user_id is null then raise exception 'Authentication required.' using errcode='42501'; end if;
  select id into v_channel_id from public.community_channels where channel_key=p_channel_key and is_active=true;
  if v_channel_id is null or not public.phase10_can_view_channel(v_channel_id) then raise exception 'Channel access denied.' using errcode='42501'; end if;
  select coalesce(max(sequence_id),0) into v_sequence from public.community_messages where channel_id=v_channel_id and moderation_status='active';
  if p_sequence_id is not null then v_sequence:=least(v_sequence,greatest(p_sequence_id,0)); end if;
  insert into public.channel_read_state (channel_id,user_id,last_read_sequence,last_read_at)
  values (v_channel_id,v_user_id,v_sequence,now())
  on conflict (channel_id,user_id) do update set last_read_sequence=greatest(public.channel_read_state.last_read_sequence,excluded.last_read_sequence),last_read_at=now();
  update public.community_notifications set read_at=coalesce(read_at,now()) where user_id=v_user_id and channel_id=v_channel_id and read_at is null;
  return v_sequence;
end;
$$;

create or replace function public.phase10_toggle_reaction(p_message_id uuid,p_emoji text)
returns boolean
language plpgsql
security definer
set search_path = public, auth, pg_temp
as $$
declare v_user_id uuid:=auth.uid(); v_channel_id uuid;
begin
  if v_user_id is null then raise exception 'Authentication required.' using errcode='42501'; end if;
  if p_emoji not in ('👍','❤️','🎯','👏','💡','✅') then raise exception 'Unsupported reaction.' using errcode='22023'; end if;
  select channel_id into v_channel_id from public.community_messages where id=p_message_id and moderation_status='active';
  if v_channel_id is null or not public.phase10_can_view_channel(v_channel_id) then raise exception 'Message access denied.' using errcode='42501'; end if;
  if exists (select 1 from public.message_reactions where message_id=p_message_id and user_id=v_user_id and emoji=p_emoji) then
    delete from public.message_reactions where message_id=p_message_id and user_id=v_user_id and emoji=p_emoji;
    return false;
  end if;
  insert into public.message_reactions (message_id,channel_id,user_id,emoji) values (p_message_id,v_channel_id,v_user_id,p_emoji);
  return true;
end;
$$;

create or replace function public.phase10_report_message(p_message_id uuid,p_reason text,p_details text default null)
returns uuid
language plpgsql
security definer
set search_path = public, auth, pg_temp
as $$
declare v_user_id uuid:=auth.uid(); v_channel_id uuid; v_report_id uuid;
begin
  if v_user_id is null then raise exception 'Authentication required.' using errcode='42501'; end if;
  if p_reason not in ('spam','harassment','misinformation','off_topic','other') then raise exception 'Invalid report reason.' using errcode='22023'; end if;
  if p_details is not null and char_length(p_details)>1000 then raise exception 'Report details are too long.' using errcode='22023'; end if;
  select channel_id into v_channel_id from public.community_messages where id=p_message_id and moderation_status='active';
  if v_channel_id is null or not public.phase10_can_view_channel(v_channel_id) then raise exception 'Message access denied.' using errcode='42501'; end if;
  insert into public.message_reports (message_id,channel_id,reporter_user_id,reason,details,status)
  values (p_message_id,v_channel_id,v_user_id,p_reason,p_details,'open')
  on conflict (message_id,reporter_user_id) do update set reason=excluded.reason,details=excluded.details,status='open',reviewed_by=null,reviewed_at=null
  returning id into v_report_id;
  return v_report_id;
end;
$$;

create or replace function public.phase10_moderate(
  p_action text,
  p_message_id uuid default null,
  p_report_id uuid default null,
  p_target_user_id uuid default null,
  p_channel_id uuid default null,
  p_reason text default null,
  p_duration_minutes integer default null
)
returns uuid
language plpgsql
security definer
set search_path = public, auth, pg_temp
as $$
declare
  v_actor uuid:=auth.uid();
  v_role text:=public.phase10_current_role();
  v_action_id uuid;
  v_channel_id uuid:=p_channel_id;
  v_target_user uuid:=p_target_user_id;
begin
  if v_actor is null or v_role not in ('moderator','admin','owner','parent_owner') then raise exception 'Moderator access required.' using errcode='42501'; end if;
  if p_reason is not null and char_length(p_reason)>500 then raise exception 'Moderation reason is too long.' using errcode='22023'; end if;

  if p_message_id is not null then
    select channel_id,user_id into v_channel_id,v_target_user from public.community_messages where id=p_message_id;
  end if;

  if p_action='delete_message' then
    if p_message_id is null then raise exception 'Message required.' using errcode='22023'; end if;
    update public.community_messages set moderation_status='moderated',deleted_at=now() where id=p_message_id;
  elsif p_action='restore_message' then
    if p_message_id is null then raise exception 'Message required.' using errcode='22023'; end if;
    update public.community_messages set moderation_status='active',deleted_at=null where id=p_message_id;
  elsif p_action='pin' then
    if p_message_id is null or v_channel_id is null then raise exception 'Message required.' using errcode='22023'; end if;
    if not exists(select 1 from public.community_messages where id=p_message_id and moderation_status='active') then raise exception 'Only active messages can be pinned.' using errcode='22023'; end if;
    insert into public.pinned_messages (channel_id,message_id,pinned_by) values (v_channel_id,p_message_id,v_actor) on conflict do nothing;
  elsif p_action='unpin' then
    if p_message_id is null then raise exception 'Message required.' using errcode='22023'; end if;
    delete from public.pinned_messages where message_id=p_message_id;
  elsif p_action='block' then
    if v_target_user is null then raise exception 'Target user required.' using errcode='22023'; end if;
    if coalesce(p_duration_minutes,0) not in (60,480,1440,2880) then raise exception 'Block duration must be 1, 8, 24 or 48 hours.' using errcode='22023'; end if;
    insert into public.chat_blocks (user_id,channel_id,blocked_by,reason,ends_at)
    values (v_target_user,p_channel_id,v_actor,coalesce(nullif(btrim(p_reason),''),'Chat violation'),now()+make_interval(mins=>p_duration_minutes));
  elsif p_action='unblock' then
    if v_target_user is null then raise exception 'Target user required.' using errcode='22023'; end if;
    update public.chat_blocks set ends_at=now() where user_id=v_target_user and ends_at>now() and (p_channel_id is null or channel_id=p_channel_id);
  elsif p_action in ('dismiss_report','resolve_report') then
    if p_report_id is null then raise exception 'Report required.' using errcode='22023'; end if;
    update public.message_reports set status=case when p_action='dismiss_report' then 'dismissed' else 'actioned' end,reviewed_by=v_actor,reviewed_at=now() where id=p_report_id;
    if not found then raise exception 'Report not found.' using errcode='22023'; end if;
  else
    raise exception 'Unsupported moderation action.' using errcode='22023';
  end if;

  if p_report_id is not null and p_action in ('delete_message','block') then
    update public.message_reports set status='actioned',reviewed_by=v_actor,reviewed_at=now() where id=p_report_id;
  end if;

  insert into public.moderation_actions (actor_user_id,actor_role,action_type,channel_id,message_id,target_user_id,report_id,reason,metadata)
  values (v_actor,v_role,p_action,v_channel_id,p_message_id,v_target_user,p_report_id,p_reason,jsonb_build_object('duration_minutes',p_duration_minutes))
  returning id into v_action_id;
  return v_action_id;
end;
$$;

