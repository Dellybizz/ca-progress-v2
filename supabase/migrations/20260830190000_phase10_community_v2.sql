create or replace function public.phase10_current_role()
returns text
language sql
stable
set search_path = public, auth, pg_temp
as $$
  select case
    when coalesce(auth.jwt() -> 'app_metadata' ->> 'role','student') in ('moderator','admin','owner','parent_owner')
      then auth.jwt() -> 'app_metadata' ->> 'role'
    else 'student'
  end;
$$;

