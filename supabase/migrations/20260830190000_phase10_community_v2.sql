-- CA Progress V2 - Phase 10 Community V2 & Collaborative Learning
-- V2 only. Phase 7 approved uploads are the only community attachment source.

create table public.community_channels (
  id uuid primary key default gen_random_uuid(),
  channel_key text not null unique check (char_length(channel_key) between 1 and 180),
  slug text not null unique check (char_length(slug) between 1 and 180),
  scope_type text not null check (scope_type in ('global','level','subject')),
  channel_kind text not null check (channel_kind in ('general','announcements','resources','result_talk','general_talk','doubts')),
  level_id text references public.course_levels(id) on delete restrict,
  subject_id text references public.subjects(id) on delete restrict,
  title text not null check (char_length(title) between 1 and 120),
  description text not null default '' check (char_length(description) <= 500),
  write_policy text not null default 'members' check (write_policy in ('members','moderators')),
  sort_order integer not null default 0,
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint community_channel_scope_shape check (
    (scope_type = 'global' and level_id is null and subject_id is null)
    or (scope_type = 'level' and level_id is not null and subject_id is null)
    or (scope_type = 'subject' and subject_id is not null)
  )
);

create table public.community_messages (
  id uuid primary key default gen_random_uuid(),
  sequence_id bigint generated by default as identity unique,
  channel_id uuid not null references public.community_channels(id) on delete restrict,
  user_id uuid not null references auth.users(id) on delete cascade,
  author_label text not null check (char_length(author_label) between 1 and 100),
  body text not null check (char_length(body) between 1 and 2000),
  reply_to_message_id uuid references public.community_messages(id) on delete set null,
  attached_resource_id uuid references public.uploaded_resources(id) on delete set null,
  moderation_status text not null default 'active' check (moderation_status in ('active','moderated','deleted')),
  edited_at timestamptz,
  deleted_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.message_reactions (
  message_id uuid not null references public.community_messages(id) on delete cascade,
  channel_id uuid not null references public.community_channels(id) on delete cascade,
  user_id uuid not null references auth.users(id) on delete cascade,
  emoji text not null check (emoji in ('👍','❤️','🎯','👏','💡','✅')),
  created_at timestamptz not null default now(),
  primary key (message_id, user_id, emoji)
);

create table public.channel_read_state (
  channel_id uuid not null references public.community_channels(id) on delete cascade,
  user_id uuid not null references auth.users(id) on delete cascade,
  last_read_sequence bigint not null default 0 check (last_read_sequence >= 0),
  last_read_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  primary key (channel_id, user_id)
);

create table public.pinned_messages (
  channel_id uuid not null references public.community_channels(id) on delete cascade,
  message_id uuid not null references public.community_messages(id) on delete cascade,
  pinned_by uuid not null references auth.users(id) on delete restrict,
  pinned_at timestamptz not null default now(),
  primary key (channel_id, message_id)
);

create table public.message_reports (
  id uuid primary key default gen_random_uuid(),
  message_id uuid not null references public.community_messages(id) on delete cascade,
  channel_id uuid not null references public.community_channels(id) on delete cascade,
  reporter_user_id uuid not null references auth.users(id) on delete cascade,
  reason text not null check (reason in ('spam','harassment','misinformation','off_topic','other')),
  details text check (details is null or char_length(details) <= 1000),
  status text not null default 'open' check (status in ('open','actioned','dismissed')),
  reviewed_by uuid references auth.users(id) on delete set null,
  reviewed_at timestamptz,
  created_at timestamptz not null default now(),
  unique (message_id, reporter_user_id)
);

create table public.chat_blocks (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references auth.users(id) on delete cascade,
  channel_id uuid references public.community_channels(id) on delete cascade,
  blocked_by uuid not null references auth.users(id) on delete restrict,
  reason text not null default 'Chat moderation' check (char_length(reason) between 1 and 500),
  starts_at timestamptz not null default now(),
  ends_at timestamptz not null,
  created_at timestamptz not null default now(),
  constraint chat_block_positive_window check (ends_at > starts_at)
);

create table public.moderation_actions (
  id uuid primary key default gen_random_uuid(),
  actor_user_id uuid not null references auth.users(id) on delete restrict,
  actor_role text not null check (actor_role in ('moderator','admin','owner','parent_owner')),
  action_type text not null check (action_type in ('delete_message','restore_message','pin','unpin','block','unblock','dismiss_report','resolve_report')),
  channel_id uuid references public.community_channels(id) on delete set null,
  message_id uuid references public.community_messages(id) on delete set null,
  target_user_id uuid references auth.users(id) on delete set null,
  report_id uuid references public.message_reports(id) on delete set null,
  reason text check (reason is null or char_length(reason) <= 500),
  metadata jsonb not null default '{}'::jsonb check (jsonb_typeof(metadata) = 'object'),
  created_at timestamptz not null default now()
);

