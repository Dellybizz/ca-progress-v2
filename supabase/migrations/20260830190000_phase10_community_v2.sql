$$;

create or replace function public.phase10_channel_visible_to_user(p_channel_id uuid, p_user_id uuid)
returns boolean
language plpgsql
stable
security definer
set search_path = public, auth, pg_temp
as $$
declare
  v_channel public.community_channels;
  v_profile public.profiles;
  v_level_code text;
  v_group_code text;
begin
  if p_user_id is null then return false; end if;
  select * into v_channel from public.community_channels where id = p_channel_id and is_active = true;
  if not found then return false; end if;
  if v_channel.scope_type = 'global' then return true; end if;
  select * into v_profile from public.profiles where user_id = p_user_id;
  if not found or v_profile.onboarding_completed_at is null then return false; end if;

  if v_channel.scope_type = 'level' then
    select code into v_level_code from public.course_levels where id = v_channel.level_id and is_active = true;
    return v_level_code is not null and v_profile.ca_level = v_level_code;
  end if;

  select cl.code, cg.code
  into v_level_code, v_group_code
  from public.subjects s
  join public.course_levels cl on cl.id = s.level_id and cl.is_active = true
  join public.course_groups cg on cg.id = s.group_id
  where s.id = v_channel.subject_id and s.is_active = true;

  if v_level_code is null or v_profile.ca_level <> v_level_code then return false; end if;
  if v_group_code = 'all' then return true; end if;
  return v_profile.group_choice = 'both' or v_profile.group_choice = v_group_code;
end;
$$;

create or replace function public.phase10_can_view_channel(p_channel_id uuid)
returns boolean
language sql
stable
security definer
set search_path = public, auth, pg_temp
as $$
  select auth.uid() is not null
    and (public.phase10_is_moderator() or public.phase10_channel_visible_to_user(p_channel_id, auth.uid()));
$$;

create or replace function public.phase10_is_chat_blocked(p_user_id uuid, p_channel_id uuid)
returns boolean
language sql
stable
security definer
set search_path = public, auth, pg_temp
as $$
  select exists (
    select 1 from public.chat_blocks b
    where b.user_id = p_user_id
      and b.starts_at <= now()
      and b.ends_at > now()
      and (b.channel_id is null or b.channel_id = p_channel_id)
  );
$$;

create or replace function public.phase10_can_write_channel(p_channel_id uuid)
returns boolean
language plpgsql
stable
security definer
set search_path = public, auth, pg_temp
as $$
declare v_policy text;
begin
  if auth.uid() is null then return false; end if;
  if not (public.phase10_is_moderator() or public.phase10_channel_visible_to_user(p_channel_id, auth.uid())) then return false; end if;
  if public.phase10_is_chat_blocked(auth.uid(), p_channel_id) then return false; end if;
  select write_policy into v_policy from public.community_channels where id = p_channel_id and is_active = true;
  if v_policy is null then return false; end if;
  return v_policy = 'members' or public.phase10_is_moderator();
end;
$$;

create or replace function public.phase10_sync_community_channels()
returns void
language plpgsql
security definer
set search_path = public, auth, pg_temp
as $$
begin
  insert into public.community_channels (channel_key,slug,scope_type,channel_kind,title,description,write_policy,sort_order,is_active)
  values ('global:general','general','global','general','General','Community-wide CA student discussion.','members',0,true)
  on conflict (channel_key) do update set title=excluded.title,description=excluded.description,is_active=true;

  insert into public.community_channels (channel_key,slug,scope_type,channel_kind,level_id,title,description,write_policy,sort_order,is_active)
  select 'level:'||cl.id||':'||kind.kind,
         lower(cl.code)||'-'||replace(kind.kind,'_','-'),
         'level',kind.kind,cl.id,kind.title,kind.description,kind.policy,kind.ordering,cl.is_active
  from public.course_levels cl
  cross join (values
    ('announcements','Announcements','Important level-specific announcements.','moderators',10),
    ('resources','Resources','Discuss approved study resources for this level.','members',20),
    ('result_talk','Result Talk','Discuss results, attempts and exam experiences.','members',30),
    ('general_talk','General Talk','Level-specific peer discussion.','members',40)
  ) as kind(kind,title,description,policy,ordering)
  on conflict (channel_key) do update set slug=excluded.slug,title=excluded.title,description=excluded.description,write_policy=excluded.write_policy,sort_order=excluded.sort_order,is_active=excluded.is_active;

  insert into public.community_channels (channel_key,slug,scope_type,channel_kind,level_id,subject_id,title,description,write_policy,sort_order,is_active)
  select 'subject:'||s.id||':doubts',
         lower(cl.code)||'-'||s.slug||'-doubts',
         'subject','doubts',s.level_id,s.id,s.title,'Subject doubts and collaborative problem solving.','members',100+s.sort_order,(s.is_active and cl.is_active)
  from public.subjects s
  join public.course_levels cl on cl.id=s.level_id
  on conflict (channel_key) do update set slug=excluded.slug,level_id=excluded.level_id,subject_id=excluded.subject_id,title=excluded.title,description=excluded.description,sort_order=excluded.sort_order,is_active=excluded.is_active;
end;
$$;

